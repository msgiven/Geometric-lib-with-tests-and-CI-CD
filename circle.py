import math


def area(r):
    '''
    Вычисляет площадь круга по заданному радиусу.

        Параметры:
            r (float/int): радуис круга.

        Возвращаемое значение:
            area (float): площадь круга. 
    '''
    return math.pi * r * r


def perimeter(r):
    '''
    Вычисляет периметр круга по заданному радиусу.

        Параметры:
                r (float/int): радуис круга.
    
        Возвращаемое значение:
            perimeter (float): периметр круга.
    '''
    return 2 * math.pi * r

